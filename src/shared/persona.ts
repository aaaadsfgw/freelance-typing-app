export function personaLineFor(id: string, difficulty: Difficulty): PersonaLine {
  const lines = PERSONA_LINES[difficulty];
  const hash = Array.from(id).reduce((sum, ch) => sum + ch.charCodeAt(0) * 17, 0);
  return lines[hash % lines.length]!;
}
