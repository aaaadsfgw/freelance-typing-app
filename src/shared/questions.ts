import type { Difficulty, Question, ReplyChunk } from "./types.ts";
import { CLIENTS, type Client } from "./clients.ts";

function q(
  id: string,
  difficulty: Difficulty,
  category: string,
  clientId: keyof typeof CLIENTS,
  projectName: string,
  requestText: string,
  pairs: Array<[string, string]>,
): Question {
  const client: Client = CLIENTS[clientId];
  const chunks: ReplyChunk[] = pairs.map(([text, kana]) => ({ text, kana }));
  return {
    id,
    difficulty,
    category,
    clientName: client.name,
    clientRole: client.role,
    clientIcon: client.avatar,
    projectName,
    requestText,
    replyText: chunks.map((c) => c.text).join(""),
    replyReading: chunks.map((c) => c.kana).join(""),
    chunks,
  };
}

