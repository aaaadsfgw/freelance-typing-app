import type { Difficulty, Question, ReplyChunk } from "./types";

function q(
  id: string,
  difficulty: Difficulty,
  category: string,
  clientName: string,
  clientRole: string,
  clientIcon: string,
  projectName: string,
  requestText: string,
  pairs: Array<[string, string]>,
): Question {
  const chunks: ReplyChunk[] = pairs.map(([text, kana]) => ({ text, kana }));
  const replyText = chunks.map((c) => c.text).join("");
  const replyReading = chunks.map((c) => c.kana).join("");
  return {
    id,
    difficulty,
    category,
    clientName,
    clientRole,
    clientIcon,
    projectName,
    requestText,
    replyText,
    replyReading,
    chunks,
  };
}

